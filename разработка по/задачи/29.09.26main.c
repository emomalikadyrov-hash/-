#include <stdio.h>

int main()
{
    int n;
    int a;
    int b;
    int i;
    int j;
    // count — счётчик
    int count;

    // 4.1
    // scanf — ввод с клавиатуры
    // ( ) — аргументы функции
    // "%d" — ввод целого числа
    // & — получить адрес переменной
    // n — куда записываем введённое число
    // ; — конец команды
    scanf("%d",&n);

    // for — цикл
    // i = 1 — начинаем с 1
    // ; — разделяет части цикла
    // i <= n — пока i меньше или равно n
    // i++ — увеличиваем i на 1
    // ( ) — условие цикла
    for (i = 1; i <= n; i++)
    {
        // if — проверка условия
        // % — остаток от деления
        // == — сравнение «равно»
        // если n делится на i без остатка
        if (n % i == 0)
        {
            // printf — вывод на экран
            // "%d" — вывод целого числа
            // i — выводим значение i
            // пробел после %d — разделяет числа
            printf("%d ", i);
        }
    }

    // \n — переход на новую строку
    printf("\n");

    // 4.2
    // вводим два целых числа
    // первое записывается в a
    // второе записывается в b
    scanf("%d %d", &a, &b);

    // начинаем проверять числа от 1 до a
    for (i = 1; i <=a; i++)
    {
        // проверяем, является ли i делителем a
        if (a % i == 0)
        {
            // проверяем, является ли i делителем b
            if (b % i == 0)
            {
                // если i делит и a, и b,
                // выводим i
                printf("%d", i);
            }
        }
    }


    // 4.3
    scanf("%d",&n);

    // перебираем числа от 2 до n
    for (i = 2; i <= n; i++)
    {
        // обнуляем счётчик делителей
        count = 0;

        // проверяем делители числа i
        for (j = 1; j <=i; j++)
        {
            // если i делится на j без остатка
            if (i % j == 0)
            {
                // увеличиваем количество делителей на 1
                // ++ означает прибавить 1
                count++;
            }
        }

        // простое число имеет ровно 2 делителя
        if (count == 2)
        {
              // выводим простое число
             printf("%d ", i);
        }

    }
    printf("\n");

    // 4.4

    // вводим два числа
    scanf("%d %d", &a, &b);

    // while — цикл
    // != означает «не равно»
    // цикл работает, пока a и b не станут равными
    while (a != b)
    {
        if (a>b)
        {
            a = a - b;
        }
        else if (b>a)
        {
            b = b - a;
        }
    }

    // когда a и b стали равными,
    // выводим a — это НОД
    printf("%d", a);

    return 0;
}















